"""Bundled example data and toy-data simulators."""

from __future__ import annotations

from pathlib import Path

from anndata import AnnData, read_h5ad

from ._simulate import simulate_clustered, simulate_niche, simulate_toy

__all__ = ["simulate_clustered", "simulate_niche", "simulate_toy", "toy_spide"]


def toy_spide() -> AnnData:
    """A small synthetic spatial data set for spiDE examples (R `toySpiDE`).

    A seeded toy data set of 20 genes across 2,400 cells from 16 patients (eight Responders,
    eight Non-responders; one sample of 150 cells each) with three cell types (A, B, C) laid out
    on a 500 x 500 field. Cell type B is concentrated in the right of the field, and a
    neighbourhood-dependent signal is planted: gene `G1` is up-regulated in the index cell
    type A, in Responders, in proportion to the local density of the niche cell type B.

    Returns
    -------
    anndata.AnnData
        Cells x genes counts in `X` and `layers["counts"]`, `obs` columns `sample_id`,
        `condition`, `x`, `y`, `cell_type`, `Age`, `cell_id`, `Area`, `nCount`
        and `obsm["spatial"]`. It is R's own object (generated by `data-raw/make_toySpiDE.R`
        with `.toySPE(n_samples = 16, n_per = 150, n_genes = 20, seed = 7)`), not a
        `simulate_toy` draw. Text columns are plain strings.
    """
    adata = read_h5ad(Path(__file__).with_name("toySpiDE.h5ad"))
    for c in adata.obs.columns:  # the file stores strings as categories; the simulators use str
        if str(adata.obs[c].dtype) == "category":
            adata.obs[c] = adata.obs[c].astype(str)
    return adata
